import fs from 'node:fs/promises'
import process from 'node:process'
import { QUESTIONS, QUIZ_ID } from '../src/data/catalog.ts'

const outputUrl = new URL('../integration/seed-social-grade1.sql', import.meta.url)
const PRODUCTION_URL = 'https://ahmad9077.github.io/social-grade1-quiz/'

function sqlText(value: string): string {
  return `'${value.replaceAll("'", "''")}'`
}

function sqlArray(values: string[]): string {
  return `array[${values.map(sqlText).join(', ')}]`
}

const rows = QUESTIONS.map((question) => {
  const topics = ['social_grade1', `topic_${question.topic}`, `kind_${question.kind}`]
  const skills = question.skills.map((skill) => skill.replaceAll('-', '_'))
  return `  (${sqlText(QUIZ_ID)}, ${sqlText(question.key)}, ${question.difficulty}, ${sqlArray(topics)}, ${sqlArray(skills)})`
})

const sql = `-- Hub registration for «الاجتماعيات - الأول الابتدائي» (first social studies test practice: the Amir, my home in my country, the flag).
-- Generated by scripts/generate-hub-seed.ts. Apply only after the production site is approved and live.
-- Registers the catalog row and adaptive question profiles. Intentionally creates no quiz_assignments.

begin;

insert into public.quizzes (id, title, url, icon, color, sort_order)
values (
  ${sqlText(QUIZ_ID)},
  'الاجتماعيات - الأول الابتدائي',
  ${sqlText(PRODUCTION_URL)},
  '🇰🇼',
  '#e3f4ea',
  150
)
on conflict (id) do update set
  title = excluded.title,
  url = excluded.url,
  icon = excluded.icon,
  color = excluded.color,
  sort_order = excluded.sort_order;

insert into public.question_difficulty_profiles (
  quiz_id,
  question_key,
  difficulty,
  topic_tags,
  skill_tags
)
values
${rows.join(',\n')}
on conflict (quiz_id, question_key) do update set
  difficulty = excluded.difficulty,
  topic_tags = excluded.topic_tags,
  skill_tags = excluded.skill_tags,
  updated_at = now();

do $$
begin
  if (select count(*) from public.question_difficulty_profiles where quiz_id = ${sqlText(QUIZ_ID)}) <> ${QUESTIONS.length} then
    raise exception '${QUIZ_ID} profile count must be exactly ${QUESTIONS.length}';
  end if;
end
$$;

commit;

select
  quiz_id,
  count(*) as seeded_questions,
  min(difficulty) as min_difficulty,
  max(difficulty) as max_difficulty
from public.question_difficulty_profiles
where quiz_id = ${sqlText(QUIZ_ID)}
group by quiz_id;
`

if (process.argv.includes('--check')) {
  const existing = await fs.readFile(outputUrl, 'utf8').catch(() => '')
  if (existing !== sql) throw new Error('Hub seed is stale. Run npm run generate:hub-seed.')
  console.log(`Hub seed is current with ${QUESTIONS.length} adaptive profiles.`)
} else {
  await fs.mkdir(new URL('../integration/', import.meta.url), { recursive: true })
  await fs.writeFile(outputUrl, sql)
  console.log(`Generated ${QUESTIONS.length} adaptive profiles at ${outputUrl.pathname}`)
}
